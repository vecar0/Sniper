export function g7Cd(mach: number): number {
  if (mach <= G7[0][0]) return G7[0][1];
  const last = G7[G7.length - 1];
  if (mach >= last[0]) return last[1];
  // 이진 탐색
  let lo = 0;
  let hi = G7.length - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (G7[mid][0] <= mach) lo = mid;
    else hi = mid;
  }
  const [m0, c0] = G7[lo];
  const [m1, c1] = G7[hi];
  return c0 + ((c1 - c0) * (mach - m0)) / (m1 - m0);
}

